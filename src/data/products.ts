// ==================== STORAGE & STOREFRONT SYNC HELPERS ====================

export const getStoredProducts = (): Product[] => {
  if (typeof window === 'undefined') return products;
  try {
    const saved = localStorage.getItem('aurelia_admin_products');
    if (saved) {
      const parsed: Product[] = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Create lookup for default catalog items
        const defaultMap = new Map(products.map((p) => [p.id, p]));
        const customProducts: Product[] = [];

        for (const item of parsed) {
          if (!defaultMap.has(item.id)) {
            // Check if this custom product is the Wave Cuff Bracelet
            const isWaveCuff =
              item.slug?.includes('wave-cuff') ||
              item.name?.toLowerCase().includes('wave cuff') ||
              item.id === 'aur-b-07';

            if (isWaveCuff) {
              customProducts.push({
                ...item,
                slug: 'wave-cuff-bracelet',
                name: item.name || 'Sculpted Wave Cuff Bracelet',
                images: [
                  '/images/products/wave_cuff_1.jpg',
                  '/images/products/wave_cuff_2.jpg',
                  '/images/products/wave_cuff_3.jpg',
                  '/images/products/wave_cuff_4.jpg',
                ],
              });
            } else {
              // Custom admin-added product: ensure its images array has its own original images
              customProducts.push(item);
            }
          } else {
            // Merge custom modifications (stock status, custom price, name) while preserving latest image assets
            const defaultProd = defaultMap.get(item.id)!;
            defaultMap.set(item.id, {
              ...defaultProd,
              inStock: item.inStock !== undefined ? item.inStock : defaultProd.inStock,
              price: item.price || defaultProd.price,
              name: item.name || defaultProd.name,
            });
          }
        }

        // Return all default catalog products + any custom user products
        return [...Array.from(defaultMap.values()), ...customProducts];
      }
    }
  } catch (e) {
    console.error('Failed to parse stored products:', e);
  }
  return products;
};

export const saveStoredProducts = (updatedProducts: Product[]): void => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('aurelia_admin_products', JSON.stringify(updatedProducts));
    window.dispatchEvent(new CustomEvent('aurelia_products_updated', { detail: updatedProducts }));
  } catch (e) {
    console.error('Failed to save stored products:', e);
  }
};

export const getProductById = (idOrSlug: string): Product | undefined => {
  const all = getStoredProducts();
  if (!idOrSlug) return undefined;

  const raw = decodeURIComponent(idOrSlug).toLowerCase().trim();
  const normalized = raw.replace(/^-+|-+$/g, '');

  return all.find((p) => {
    const pId = p.id.toLowerCase();
    const pSlug = p.slug.toLowerCase();
    const pSlugNorm = pSlug.replace(/^-+|-+$/g, '');

    return (
      pId === raw ||
      pSlug === raw ||
      pSlugNorm === normalized ||
      (normalized.length >= 3 && (pSlugNorm.includes(normalized) || normalized.includes(pSlugNorm)))
    );
  });
};


export const getProductsByCategory = (category: string): Product[] => {
  const all = getStoredProducts();
  if (category === 'all') return all;
  return all.filter((p) => p.category === category);
};

export const getProductsByCollection = (collection: string): Product[] => {
  const all = getStoredProducts();
  if (collection === 'anti-tarnish') return all.filter((p) => p.isAntiTarnish);
  if (collection === 'new-arrivals') return all.filter((p) => p.isNew);
  if (collection === 'best-sellers') return all.filter((p) => p.isBestSeller);
  if (collection === 'minimalist') return all.filter((p) => p.collection === 'minimalist');
  return all;
};

export const getBestSellers = (): Product[] => {
  const all = getStoredProducts();
  return all.filter((p) => p.isBestSeller);
};

export const getNewArrivals = (): Product[] => {
  const all = getStoredProducts();
  return all.filter((p) => p.isNew);
};

